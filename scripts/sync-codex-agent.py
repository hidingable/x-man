#!/usr/bin/env python3
"""Render one x-mansion Markdown agent as an official Codex TOML agent."""

import argparse
import json
import pathlib
import re


MARKER = "# Generated by x-mansion"


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True)
    parser.add_argument("--target", required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--resources", required=True)
    return parser.parse_args()


def read_agent(source, name, resources):
    text = pathlib.Path(source).read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"agent front-matter 非法: {name}.md")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError(f"agent front-matter 非法: {name}.md")

    description = None
    for line in text[4:end].splitlines():
        if not line.startswith("description:"):
            continue
        raw = line.split(":", 1)[1].strip()
        if raw.startswith('"') and raw.endswith('"'):
            description = json.loads(raw)
        elif raw.startswith("'") and raw.endswith("'"):
            description = raw[1:-1].replace("''", "'")
        else:
            description = raw
        break
    if not description:
        raise ValueError(f"agent 缺少 description: {name}.md")

    instructions = text[end + len("\n---\n"):].strip()
    if "'''" in instructions:
        raise ValueError(f"agent 正文包含 TOML 多行字符串终止符: {name}.md")
    resource_path = pathlib.Path(resources).resolve().as_posix()
    # Rewrite companion-relative paths, not same-named artifact or URL segments.
    instructions = re.sub(
        rf"(?<![\w./\\:-]){re.escape(name)}/",
        lambda match: f"{resource_path}/",
        instructions,
    )
    if "`context/conventions.md`" in instructions:
        conventions = pathlib.Path(source).resolve().parent.parent / "context" / "conventions.md"
        if not conventions.is_file():
            raise ValueError(f"agent 随附约定缺失: {conventions}；恢复源文件后重新安装")
        instructions = instructions.replace("`context/conventions.md`", f"`{conventions.as_posix()}`")

    source_root = pathlib.Path(source).resolve().parent.parent

    def resolve_repository_reference(match):
        reference = source_root / match.group(1)
        return f"`{reference.resolve().as_posix()}`" if reference.is_file() else match.group(0)

    # Declared source resources must remain readable from another project cwd.
    instructions = re.sub(
        r"`((?:skills|context)/[^`\n]+\.md)`", resolve_repository_reference, instructions,
    )
    return description, instructions


def main():
    args = parse_args()
    description, instructions = read_agent(args.source, args.name, args.resources)
    target = pathlib.Path(args.target)
    target.parent.mkdir(parents=True, exist_ok=True)
    content = "\n".join([
        f"{MARKER} — source: {pathlib.Path(args.source).resolve().as_posix()}",
        f"name = {json.dumps(args.name, ensure_ascii=False)}",
        f"description = {json.dumps(description, ensure_ascii=False)}",
        "developer_instructions = '''",
        instructions,
        "'''",
        "",
    ])
    target.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
